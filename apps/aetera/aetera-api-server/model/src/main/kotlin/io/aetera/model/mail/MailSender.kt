 * 종류마다 포트를 두면 로그·메일 발송기 한 쌍이 종류만큼 복제되고, 그중 하나만
 * 고치는 날이 온다.
 *
 * 보내다 실패하면 던진다 — 삼키면 부르는 쪽이 "보냈다"고 여겨, 못 간 메일이 조용히 사라진다.
 */
