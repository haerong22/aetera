package io.aetera.model.spending

/**
 * 평균과 **그것을 몇 달로 냈는지**.
 *
 * 둘을 함께 들고 다니는 이유 — 금액만 주면 받는 쪽이 그 숫자를 얼마나 믿을지 알 수 없다.
 * 두 달치 평균을 "평소"로 읽으면 퇴사 준비의 런웨이가 그만큼 흔들리는데, 보는 사람은
 * 그 사실을 알 길이 없다.
 *
 * 처음엔 평균과 달 수를 따로 계산했다. 그러자 창(최근 몇 달)을 두 곳에서 세게 되어
 * **한쪽만 바뀌면 "6개월 평균"이라 적힌 값이 실제로는 세 달치**가 될 수 있었다 —
 * 신뢰도를 밝히려고 만든 값이 거짓말을 하는 셈이다. 그래서 한 번에 센다.
 */
data class MonthlyAverage(
    val amount: Long,
    /** 평균에 실제로 센 달 수. 창의 길이가 아니라 **기록이 있던 달의 수**다. */
    val months: Int,
) {
    init {
        require(months > 0) { "센 달이 없으면 평균을 만들지 않는다" }
    }
}
