package io.aetera.model.auth

/**
 * 리프레시 토큰이 폐기된 이유.
 *
 * 회전으로 죽은 토큰만 짧은 유예를 받는다. 이 구분이 없으면 탈취 대응으로 방금 끊어 놓은
 * 토큰들까지 "회전 직후"로 취급돼 그대로 되살아난다 — 대응이 통째로 무력해진다.
 */
enum class RefreshTokenRevocation {
    /** 정상 재발급으로 교체됐다. 동시 요청 경합을 감안해 짧은 유예를 준다. */
    ROTATED,

    /** 로그아웃이나 탈취 대응으로 끊었다. 유예 없이 즉시 무효다. */
    REVOKED,
}
