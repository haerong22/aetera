-- 리프레시 토큰이 왜 폐기됐는지 구분한다.
--
-- 회전(ROTATED)으로 죽은 토큰만 아주 짧은 유예를 받는다. 탭 여러 개가 동시에 재발급을
-- 시도하는 정상 경합을 탈취로 오인하지 않기 위해서다. 반대로 로그아웃이나 탈취 대응으로
-- 끊은 토큰(REVOKED)은 유예 없이 즉시 무효여야 한다 — 구분이 없으면 방금 끊은 세션이
-- 유예 덕분에 되살아나 탈취 대응이 통째로 무력해진다.
--
-- 기존 행은 null 로 남는데, 유예는 ROTATED 에만 주므로 null 은 자동으로 "유예 없음"이 된다.

alter table refresh_tokens
    add column revoked_reason varchar(20);
